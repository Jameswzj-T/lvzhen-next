import { written } from "../criminal-package-one/authoring";

type Point = [string, string, string];
type Question = {
  topicId: string;
  prompt: string;
  points: Point[];
  related?: string[];
  sources?: string[];
};
function longCase(
  id: string,
  title: string,
  paragraphs: string[],
  questions: Question[],
) {
  const facts = paragraphs.join("\n\n");
  return {
    id,
    title,
    facts,
    cases: questions.map((q, i) => {
      const item = written(
        `${id}-q${i + 1}`,
        q.topicId,
        `${title} · 第${i + 1}问`,
        facts,
        q.prompt,
        q.points.map((p) => p[1]).join("\n"),
        q.points,
        { related: q.related, sources: q.sources ?? ["law"] },
      );
      item.exercise.caseId = id;
      return item;
    }),
  };
}

