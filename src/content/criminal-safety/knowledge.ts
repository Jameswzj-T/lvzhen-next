export const safetyKnowledge: Record<
  string,
  { rule: string; omission: string }
> = Object.fromEntries(
  cards.map(({ id, rule, omission }) => [id, { rule, omission }]),
);

export const safetyTopics: FaultTopic[] = cards.map((c) => ({
  id: c.id,
  title: c.title,
  headline: c.title,
  goal: c.rule,
  prerequisite: "可直接查看要点或进入练习。",
  minutes: "3–5",
  paragraphs: [c.rule, c.omission],
  pitfall: c.omission,
  example: { title: "一个区别", facts: c.example, analysis: c.analysis },
  recall: { prompt: "这一知识的适用条件是什么？", reference: c.rule },
  sources: c.sources,
  exercises: safetyCases
    .filter((cse) => cse.topicId === c.id)
    .map((cse) => cse.exercise),
}));
