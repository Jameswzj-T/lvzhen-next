export function civilTrafficMedicalQuestion(id: string) {
  const question = civilTrafficMedicalExercises.find((q) => q.id === id);
  return question ? structuredClone(question) : undefined;
}
export function civilTrafficMedicalTopicForQuestion(id: string) {
  return civilTrafficMedicalTopics.find((topic) =>
    topic.exercises.some((q) => q.id === id),
  );
}
export function civilTrafficMedicalSameCaseQuestions(id: string) {
  const question = civilTrafficMedicalQuestion(id);
  return question
    ? structuredClone(
        civilTrafficMedicalExercises.filter(
          (q) => q.caseId === question.caseId,
        ),
      )
    : [];
}
export function civilTrafficMedicalChapterQueue(
  chapterId: string,
  mode: "objective" | "subjective",
) {
  const chapter = civilTrafficMedicalChapters.find((c) => c.id === chapterId);
  return chapter
    ? civilTrafficMedicalTopics
        .filter((t) => chapter.topicIds.includes(t.id))
        .flatMap((t) => t.exercises)
        .filter((q) => q.kind === mode)
        .map((q) => q.id)
    : [];
}
