export const civilServiceContractDefaultQueues = {
  objective: civilServiceContractExercises
    .filter((q) => q.kind === "objective")
    .map((q) => q.id),
  subjective: civilServiceContractExercises
    .filter((q) => q.kind === "subjective")
    .map((q) => q.id),
};
export function civilServiceContractQuestion(id: string) {
  const question = civilServiceContractExercises.find((q) => q.id === id);
  return question ? structuredClone(question) : undefined;
}
export function civilServiceContractTopicForQuestion(id: string) {
  return civilServiceContractTopics.find((topic) =>
    topic.exercises.some((q) => q.id === id),
  );
}
export function civilServiceContractSameCaseQuestions(id: string) {
  const question = civilServiceContractQuestion(id);
  return question
    ? structuredClone(
        civilServiceContractExercises.filter(
          (q) => q.caseId === question.caseId,
        ),
      )
    : [];
}
export function civilServiceContractChapterQueue(
  chapterId: string,
  mode: "objective" | "subjective",
) {
  const chapter = civilServiceContractChapters.find((c) => c.id === chapterId);
  return chapter
    ? civilServiceContractTopics
        .filter((t) => chapter.topicIds.includes(t.id))
        .flatMap((t) => t.exercises)
        .filter((q) => q.kind === mode)
        .map((q) => q.id)
    : [];
}
